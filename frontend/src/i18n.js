let LANG = (() => { try { return localStorage.getItem("imibavu_lang") || "en"; } catch (e) { return "en"; } })();

export function getLang() { return LANG; }

export function t(key) {
  return (I18N[LANG] && I18N[LANG][key]) || I18N.en[key] || key;
}

/* Called by the store so every component re-renders on language change. */
export function setLangVar(lang) {
  LANG = I18N[lang] ? lang : "en";
  try { localStorage.setItem("imibavu_lang", LANG); } catch (e) { /* ignore */ }
  if (typeof document !== "undefined") document.documentElement.setAttribute("lang", LANG);
}